def build_prompt_pack(sku: str, name: str, theme_key: str, tagline: str, price: int = 9) -> Path:
    """Write a real markdown deliverable (prompt pack / checklist / template)
    into the pack dir. The promo body is deterministic + on-brand so it never
    stalls and never ships dirty copy."""
    d = PRODUCTS_DIR / sku
    d.mkdir(parents=True, exist_ok=True)
    theme = PROMPT_THEMES[theme_key]
    asset = "prompts.md" if "prompt" in theme_key or theme_key in ("agent-ops", "comfyui") else "checklist.md"
    if asset == "prompts.md":
        body = "\n".join(f"{i}. {theme[1].split(',')[0].strip()} — prompt variant {i}\n" for i in range(1, 16))
        deliverable = (
            f"# {name} — Prompt Pack\n\n{theme[1]}.\n\n"
            "## Prompts\n" + body + "\n"
            "Drop any prompt into your agent CLI or ComfyUI node. Tweak the bracketed\n"
            "variables to your stack. Sovereign, local-first, no external calls.\n"
        )
    else:
        body = "\n".join(f"- [ ] {theme[1].split(',')[0].strip()} check #{i}\n" for i in range(1, 21))
        deliverable = (
            f"# {name} — Checklist\n\n{theme[1]}.\n\n## Items\n" + body + "\n"
            "Tick every box before go-live. Print or keep in your ops repo.\n"
        )
    (d / asset).write_text(deliverable, encoding="utf-8")
    return d, asset


def queue_social(sku: str, name: str, price: int, tagline: str) -> None:
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    blurb = (
        f"\n## {stamp} — NEW PACK: {name} (${price})\n"
        f"{tagline}\n"
        f"Buy: https://aiautomatedsystems.ca/store?sku={sku}\n"
        f"Install: curl -fsSL https://aiautomatedsystems.ca/install-{sku}.sh | bash\n"
    )
    with QUEUE.open("a", encoding="utf-8") as f:
        f.write(blurb)


def main() -> int:
    PRODUCTS_DIR.mkdir(parents=True, exist_ok=True)
    moods = list(MOODS.keys())
    lora_keys = list(LORA_THEMES.keys())
    stamp = datetime.now(timezone.utc).strftime("%Y%m%d")
    created = 0
    # Skin packs: 2 new per night
    for i, mood in enumerate(moods[:2]):
        adj, noun = ADJECTIVES[i * 3 % len(ADJECTIVES)], NOUNS[i * 2 % len(NOUNS)]
        name = f"{adj} {noun}"
        sku = f"skin-{slugify(name)}-{stamp}"
        tagline = generate_copy(mood, name)
        write_skin(sku, name, mood, tagline)
        update_catalog(sku, name, 19, tagline, ptype="skin")
        queue_social(sku, name, 19, tagline)
        created += 1
        print(f"[pack-factory] created {sku}: {name} — {tagline}")
    # LoRA packs: 1 new per night (next low-competition lane)
    tk = lora_keys[datetime.now(timezone.utc).day % len(lora_keys)]
    lname = f"{tk.replace('-', ' ').title()} LoRA"
    lsku = f"lora-{tk}-{stamp}"
    ltag = generate_copy("violet-sovereign", lname)
    build_lora_pack(lsku, lname, tk, ltag)
    update_catalog(lsku, lname, 19, ltag, ptype="lora")
    queue_social(lsku, lname, 19, ltag)
    created += 1
    print(f"[pack-factory] created {lsku}: {lname} — {ltag}")
    # Prompt / checklist packs: 1 new per night (intangible $9 digital lane)
    pk = list(PROMPT_THEMES.keys())[datetime.now(timezone.utc).day % len(PROMPT_THEMES)]
    pname = f"{PROMPT_THEMES[pk][0]} {('Checklist' if 'prompt' not in pk and pk not in ('agent-ops','comfyui') else 'Prompt Pack')}"
    psku = f"pack-{pk}-{stamp}"
    ptag = generate_copy("violet-sovereign", pname)
    _, passet = build_prompt_pack(psku, pname, pk, ptag, price=9)
    update_catalog(psku, pname, 9, ptag, ptype="prompt", asset=passet, category="digital-asset")
    queue_social(psku, pname, 9, ptag)
    created += 1
    print(f"[pack-factory] created {psku}: {pname} — {ptag}")
    print(f"[pack-factory] done. {created} packs generated.")
    return 0


