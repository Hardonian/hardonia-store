def update_catalog(sku: str, name: str, price: int, tagline: str, ptype: str = "skin", asset: str = "skin.yaml", category: str = "agent-skin") -> None:
    """Write store-standard product.json into the pack dir (matches the other
    42 products: slug/name/price/checkout_url/readiness_score/...). Auto-gen
    packs are 'draft' (score 40) pending operator review; flip to 'ready' by hand."""
    d = PRODUCTS_DIR / sku
    if ptype == "lora":
        category = "comfyui-lora"; asset = "lora.yaml"
        audience = "sovereign AI operators running ComfyUI / SDXL"
    elif ptype == "prompt":
        audience = "solo AI founders and operators"
    else:
        audience = "sovereign AI operators running Hermes / local agent fleets"
    deliverable = f"{asset} (drop-in digital deliverable)" if ptype == "prompt" else (
        "lora.yaml (ComfyUI metadata + trigger word + recommended strength), README.md"
        if ptype == "lora" else "skin.yaml (drop-in agent theme)"
    )
    product = {
        "slug": sku,
        "name": name,
        "status": "draft",
        "audience": audience,
        "pain": "generic, unbranded outputs; no style identity separation between fleets or clients",
        "offer": f"{name}: a drop-in {asset} that themes the workflow from one file.",
        "price": f"${price} one-time",
        "headline": tagline,
        "checkout_url": "https://buy.stripe.com/TODO_PASTE_REAL_STRIPE_PAYMENT_LINK",
        "gumroad_url": "https://buy.stripe.com/TODO_PASTE_REAL_STRIPE_PAYMENT_LINK",
        "image_path": f"{d}/assets/cover.png",
        "deliverable_path": f"{d}/{asset}",
        "category": category,
        "updated_at": datetime.now(timezone.utc).isoformat(),
        "readiness_score": 40,
        "source": f"{d}/product.json",
        "launch_gate": "draft: operator review of tagline + palette before promotion",
        "sku": sku,
    }
    (d / "product.json").write_text(json.dumps(product, indent=2) + "\n", encoding="utf-8")


