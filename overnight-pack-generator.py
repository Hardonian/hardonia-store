ANSI_RE = re.compile(r"\x1b\[[0-9;]*m")


def _sanitize(text: str) -> str:
    # Strip ANSI escape codes and any other non-printable control chars.
    text = ANSI_RE.sub("", text)
    return "".join(ch for ch in text if ch == "\n" or ord(ch) >= 0x20)


def ollama_generate(prompt: str) -> str | None:
    # Intentionally disabled for production copy: local chat models emit
    # terminal codes and prompt echoes that corrupt deliverables. The
    # deterministic templated fallback in generate_copy() is reliable and
    # on-brand, so we don't risk shipping dirty copy. Re-enable only with a
    # sanitized, instruction-tuned model + strict output validation.
    return None


def generate_copy(mood: str, name: str) -> str:
    prompt = (
        f"Name an AI-agent command-line skin pack called '{name}' with a {mood} aesthetic. "
        f"Return ONE sentence tagline (max 18 words) for an operator who runs sovereign local AI at 2am. "
        f"No markdown, no quotes."
    )
    txt = ollama_generate(prompt)
    if txt:
        # keep first sentence, clamp length, collapse whitespace
        tag = txt.split(".", 1)[0].strip().rstrip('"')
        tag = " ".join(tag.split())
        # reject prompt echoes / meta text
        if 10 < len(tag) < 140 and "tagline" not in tag.lower() and not tag.lower().startswith("name an"):
            return tag
    return f"{mood.replace('-', ' ').title()} command surface for operators running sovereign AI fleets at 2am."


